#!/usr/bin/env python3
"""Validate current R952 split CLI and R929 staged training contracts.

Requires an explicit synthetic production-export fixture generated by the real
RawUpstreamHarnessR932 (at least 120 issues). No deprecated R925 ACTIONS/run shim
is added. Outputs are engineering test artifacts and grant no REAL authority.
"""
from pathlib import Path
import argparse, copy, hashlib, importlib.util, json, os, subprocess, sys

def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def main():
 parser=argparse.ArgumentParser(description=__doc__)
 parser.add_argument('--project-root',type=Path,default=Path(__file__).resolve().parents[2])
 parser.add_argument('--r929-export',type=Path,required=True)
 parser.add_argument('--out',type=Path,required=True)
 a=parser.parse_args();root=a.project_root.resolve();out=a.out.resolve();source=a.r929_export.resolve();out.mkdir(parents=True,exist_ok=False)
 sys.path.insert(0,str(root));from training.r929 import pipeline as p
 spec=importlib.util.spec_from_file_location('actual_r952_split_cli',root/'training/r925/pipeline.py');split=importlib.util.module_from_spec(spec);spec.loader.exec_module(split)
 checks=[];commands=[]
 def check(value,name):
  if not value:raise AssertionError(name)
  checks.append(name);print(name+'=PASS',flush=True)
 def rejects(fn,name):
  try:fn()
  except (ValueError,RuntimeError):check(True,name);return
  raise AssertionError(name+' accepted')
 env=dict(os.environ);env['PYTHONPATH']=str(root);env['PYTHONDONTWRITEBYTECODE']='1';env['STARCORE_EXPERIMENT_REGISTRY']=str(out/'synthetic-registry');env['OPENBLAS_NUM_THREADS']='1';env['OMP_NUM_THREADS']='1'
 def cli(name,args,expected=0):
  command=[sys.executable,*map(str,args)];log=out/(name+'.log')
  with log.open('w') as stream:result=subprocess.run(command,stdout=stream,stderr=subprocess.STDOUT,env=env,cwd=root,timeout=600)
  commands.append({'name':name,'argv':command,'exit_code':result.returncode,'log_sha256':sha(log)})
  if (result.returncode==0)!=(expected==0):raise AssertionError(name+':'+log.read_text()[-3000:])
  return log
 # Current R952 CLI uses flat per-action rows, not the retired R925 model API.
 flat=[]
 for issue in range(2,32):
  for ordinal in range(1200):flat.append({'target_issue':f'20261016{issue:04d}','max_source_issue':f'20261016{issue-1:04d}','ordinal':ordinal,'verification_fixture':True})
 flatpath=out/'r952-synthetic-input.jsonl';flatpath.write_text(''.join(json.dumps(x,separators=(',',':'))+'\n' for x in flat))
 cli('r952-split-positive',[root/'training/r925/pipeline.py',flatpath,'--out',out/'r952-splits'])
 manifest=json.loads((out/'r952-splits/dataset_manifest.json').read_text());check(manifest['source_hash']==sha(flatpath),'R952_CLI_BINDS_EXACT_SOURCE_BYTES')
 issue_sets=[]
 for stage in split.STAGES:
  path=out/'r952-splits'/(stage.lower()+'.jsonl');rows=[json.loads(x) for x in path.read_text().splitlines()];groups={x['target_issue'] for x in rows};issue_sets.append(groups)
  check(all(sum(x['target_issue']==issue for x in rows)==1200 for issue in groups),'R952_'+stage+'_KEEPS_WHOLE_1200_ISSUE_GROUP')
  check(manifest['stages'][stage]['hash']==sha(path),'R952_'+stage+'_PERSISTED_STAGE_HASH')
 check(all(not a.intersection(b) for i,a in enumerate(issue_sets) for b in issue_sets[i+1:]),'R952_FIVE_STAGE_ISSUES_DISJOINT')
 check(all(max(a)<min(b) for a,b in zip(issue_sets,issue_sets[1:])),'R952_FIVE_STAGE_CHRONOLOGICAL_ORDER')
 bad=copy.deepcopy(flat[:1]);bad[0]['max_source_issue']=bad[0]['target_issue'];badpath=out/'r952-pit-invalid.jsonl';badpath.write_text(json.dumps(bad[0])+'\n');cli('r952-pit-rejection',[root/'training/r925/pipeline.py',badpath,'--out',out/'r952-pit-invalid'],expected=1);check(True,'R952_REAL_CLI_REJECTS_POSTTARGET_SOURCE')
 rejects(lambda:split.validate([flat[0],flat[0]]),'R952_DUPLICATE_TARGET_ORDINAL_REJECTED');rejects(lambda:split.split(flat[:1200]),'R952_TOO_FEW_DISTINCT_ISSUES_REJECTED')
 # Actual immutable R929 export contract and PIT negatives.
 first=source.open().readline();row=p.read_integrity_row(first);p.validate_row(row,'',None);check(True,'R929_REAL_EXPORT_PASSES_FULL1200_META96_PIT_CONTRACT')
 for name,change in [
  ('GROUP_NOT_1200',lambda r:r.update(actions=r['actions'][:10])),
  ('PIT_SOURCE_NOT_BEFORE_TARGET',lambda r:r.update(max_source_issue=r['target_issue'])),
  ('POSTDRAW_FEATURE_FREEZE',lambda r:r.update(frozen_at=r['draw_at'])),
  ('INVALID_PERMUTATION',lambda r:r.update(actual=[1]*10)),
  ('SCHEMA_OR_GAME_MISMATCH',lambda r:r.update(game='Ethereum1-PK10'))]:
  changed=copy.deepcopy(row);change(changed)
  if name=='SCHEMA_OR_GAME_MISMATCH':
   changed.pop('payload_sha256',None);text=json.dumps(changed,separators=(',',':'));text=text[:-1]+',"payload_sha256":"'+p.digest(text.encode())+'"}';rejects(lambda:p.read_integrity_row(text),'R929_'+name+'_REJECTED')
  else:rejects(lambda:p.validate_row(changed,'',None),'R929_'+name+'_REJECTED')
 changed=copy.deepcopy(row);changed['actions'][0][4][0]=float('nan');rejects(lambda:p.validate_row(changed,'',None),'R929_NONFINITE_FEATURE_REJECTED')
 rejects(lambda:p.read_integrity_row(first.replace('"payload_sha256":"','"payload_sha256":"0',1)),'R929_EXPORT_PAYLOAD_HASH_TAMPER_REJECTED')
 models=out/'r929-staged-models'
 for stage in ['dataset','number','gate','ranker','calibration','predictability','policy','evaluate']:
  arguments=['-m','training.r929.pipeline',stage,'--out',models]
  if stage=='dataset':arguments.extend(['--input',source])
  cli('r929-stage-'+stage,arguments);check(True,'R929_REAL_CLI_STAGE_'+stage.upper()+'_EXECUTED')
 dataset=p.read_json(models/'dataset_manifest.json');check(dataset['group_size']==1200 and dataset['statistical_unit']=='target_issue','R929_STATISTICAL_UNIT_IS_ISSUE_NOT_1200_ACTIONS')
 check(dataset['issues']>=120 and dataset['raw_upstream_complete_for_all_rows'],'R929_DIRECT_RAW_TENSORS_COMPLETE_NO_META_INVERSION')
 ranges=[dataset['splits'][name] for name in ['train','tune','calibration','policy','sealed']];check(all(a[1]+1==b[0] for a,b in zip(ranges,ranges[1:])),'R929_WHOLE_ISSUE_EMBARGO_BETWEEN_FIVE_SPLITS')
 number=p.read_json(models/'number_stage.json');gate=p.read_artifact(models/'gate_stage.json');rank=p.read_artifact(models/'ranker_artifact.json');cal=p.read_artifact(models/'calibration_artifact.json');policy=p.read_artifact(models/'policy_artifact.json');sealed=p.read_json(models/'sealed_evaluation.json')
 check(number['status']=='NUMBER_FAMILY_COMPARISON_COMPLETE' and gate['status']=='GATE9_TUNE_FROZEN','R929_NUMBER_AND_GATE_REAL_TRAINERS_FINISHED')
 check(cal['ranker_sha256']==rank['artifact_sha256'] and policy['calibration_sha256']==cal['artifact_sha256'],'R929_RANK_CALIBRATION_POLICY_EXACT_ARTIFACT_CHAIN')
 check(not policy['production_authority'] and not policy['forced_bet'] and not policy['frequency_debt'] and not policy['chase'],'R929_POLICY_HAS_NO_FORCED_REAL_OR_DEBT')
 check(sealed['future_live_n']==0 and sealed['model_proven'] is False,'R929_SYNTHETIC_SEALED_RESULT_GRANTS_NO_FUTURE_OR_MODEL_PROOF')
 report={'status':'PASS','scope':'CURRENT_R952_CLI_AND_R929_ACTUAL_TRAINERS_ON_EXPLICIT_SYNTHETIC_PRODUCTION_EXPORT_NOT_NATURAL_FUTURE_OR_ANDROID','checks':checks,'passed':len(checks),'commands':commands,'input_export_sha256':sha(source),'training_sources_sha256':{str(x.relative_to(root)):sha(x) for x in sorted((root/'training').rglob('*.py')) if '__pycache__' not in x.parts},'effect_proven':False,'may_authorize_real':False,'test_only_fixture':True}
 (out/'TRAINING_CONTRACT_VALIDATION.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n');print('CURRENT_TRAINING_CONTRACT_PASS checks='+str(len(checks)))
if __name__=='__main__':main()

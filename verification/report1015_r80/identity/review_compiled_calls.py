#!/usr/bin/env python3
"""Review actual producer freeze inputs; never synthesize a call fingerprint."""
from pathlib import Path
import argparse,gzip,hashlib,importlib.util,json
R=Path(__file__).resolve().parents[3];E=Path(__file__).resolve().parent
p=argparse.ArgumentParser();p.add_argument('--prepare-evidence',type=Path,required=True);a=p.parse_args();ev=a.prepare_evidence.resolve()
H=lambda x:hashlib.sha256(x.read_bytes()).hexdigest()
commands=json.loads((ev/'prepare-commands.json').read_text())
compile_records=[x for x in commands if x['log']=='bootstrap-actual-gradle-compile-NOT-APK.log']
freeze_records=[x for x in commands if x['log']=='freeze-actual-compiled-calls.log']
assert len(compile_records)==len(freeze_records)==1,'ACTUAL_PRODUCER_RECEIPTS_REQUIRED'
compile_record,freeze=compile_records[0],freeze_records[0]
for x in (compile_record,freeze):
 assert x['exitCode']==0 and H(ev/x['log'])==x['logSha256'],'PRODUCER_COMMAND_OR_LOG_NOT_VERIFIED'
assert ':app:compileReleaseJavaWithJavac' in compile_record['argv'],'RELEASE_VARIANT_REQUIRED'
args=freeze['argv'];assert args[1:4]==['scripts/r982_source_call_asset.py','--freeze','--classes'],'UNEXPECTED_FREEZE_COMMAND'
classes=Path(args[4]);assert classes.resolve()==R/'app/build/intermediates/javac/release/compileReleaseJavaWithJavac/classes'
assert list(classes.rglob('*.class')),'ACTUAL_COMPILED_CLASSES_MISSING'
archive=R/'release/r982_source_calls.tsv.gz';pinpath=R/'release/r982_source_calls.manifest.json';pin=json.loads(pinpath.read_text())
raw=gzip.decompress(archive.read_bytes());assert hashlib.sha256(raw).hexdigest()==pin['sha256'] and len(raw)==pin['bytes']
assert pin['scope']=='STATIC_COMPILED_CALLS_NOT_RUNTIME_COVERAGE'
s=importlib.util.spec_from_file_location('calls',R/'scripts/r982_source_call_asset.py');m=importlib.util.module_from_spec(s);s.loader.exec_module(m)
m.source_binding(R/'app/build/generated/assets/r982/research/r975_source_calls.tsv')
assert f"SOURCE_CALL_ASSET_VERIFIED|bytes={pin['bytes']}|sha256={pin['sha256']}" in (ev/freeze['log']).read_text()
old=json.loads((E/'prepare_input_snapshot.json').read_text())['files']
roles={x['path']:x['role']for x in json.loads((R/'release/research_dependencies_r967.json').read_text())['files']}
records=[]
for path in (archive,pinpath):
 name=path.relative_to(R).as_posix();actual=H(path)
 assert old.get(name)!=actual,'REVIEW_REFRESH_ONLY_FOR_CHANGED_GENERATED_INPUT'
 reason='Actual release-variant Gradle compiled source-call evidence regenerated by the unchanged r982 freeze producer after exact source review. Producer compile and freeze exit codes, log hashes, complete current Java source binding and decompressed archive hash/length are verified. Static compiled calls only, not runtime coverage; no Future/calibration/certificate migration.'
 assert roles[name]=='PROVENANCE','GENERATED_CALL_INPUT_CLASSIFICATION_DRIFT'
 records.append({'path':name,'before_sha256':old.get(name,''),'after_sha256':actual,'rationale':reason})
(E/'compiled_call_review.json').write_text(json.dumps({'scope':'ACTUAL_RELEASE_COMPILED_STATIC_CALLS_ONLY','producer_evidence':str(ev.relative_to(R)),'producer_commands': [compile_record,freeze],'generator_sha256':H(R/'scripts/r982_source_call_asset.py'),'index_generator_sha256':H(R/'scripts/r975_source_call_index.py'),'archive_content_sha256':pin['sha256'],'archive_content_bytes':pin['bytes'],'review':records},indent=2)+'\n')
print('ACTUAL_COMPILED_CALL_PROVENANCE_REVIEWED; numeric proof unchanged by PROVENANCE inputs')

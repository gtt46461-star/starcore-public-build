    "$OUT/R922_SOURCE_SUBSTANCE_AUDIT.txt" SOURCE_AUDIT
pass_line '^R922_COMPILE_HOST=PASS\|VERSION=V57\.20\.8-R5\.3\.8-922\|VERSION_CODE=577240922\|JAVA=[0-9]+\|CLASS=[0-9]+$' \
    "$OUT/R922_COMPILE_HOST_SUMMARY.txt" JAVA17_FULL_COMPILE

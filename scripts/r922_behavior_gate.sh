#!/usr/bin/env bash
set -euo pipefail

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
OUT=${R922_EVIDENCE_DIR:-"$ROOT/build/r922-verification/evidence"}
AUDIT=${R922_SOURCE_AUDIT_DIR:-"$ROOT/build/r922-verification/source-audit"}
mkdir -p "$OUT" "$AUDIT"
cd "$ROOT"

fail() {
    echo "R922_BEHAVIOR_GATE=FAIL|$1" >&2
    exit 1
}

pass_line() {
    local pattern=$1
    local file=$2
    local code=$3
    rg -q -- "$pattern" "$file" || fail "$code"
}

python3 verification/r922/r922_static_contract.py > "$OUT/R922_STATIC_CONTRACT.txt"
python3 verification/r919/r919_sqlite_truth_closure.py > "$OUT/R922_SQLITE_TRUTH_CLOSURE.txt"
python3 verification/r915/r915_sqlite_closed_loop.py > "$OUT/R922_R915_SQLITE_REGRESSION.txt"
python3 verification/r914/r914_end_to_end_settlement_gate.py \
    > "$OUT/R922_EVERY_DRAW_SETTLEMENT_REGRESSION.txt"
python3 verification/r911/r911_sqlite_runtime_gate.py \
    > "$OUT/R922_SQLITE_MIGRATION_RUNTIME.txt"
python3 verification/r911/r911_settlement_state_machine.py \
    > "$OUT/R922_SETTLEMENT_STATE_MACHINE.txt"
python3 verification/r910/r910_settlement_core_isolation.py \
    > "$OUT/R922_SIDECAR_FAILURE_INJECTION.txt"
python3 verification/r912/r912_settlement_fairness.py \
    > "$OUT/R922_BACKLOG_FAIRNESS.txt"
python3 verification/r912/r912_sqlite_truth_and_research.py \
    > "$OUT/R922_SQLITE_TRUTH_RESEARCH.txt"

R915_BASE_COMMIT=${R922_BASE_COMMIT:-c53ec8e46c78f2b4ee83af83079badf1d0fcb1ba} \
R915_SOURCE_AUDIT_DIR="$AUDIT" \
SOURCE_AUDIT_PREFIX=R922 \
python3 verification/r915/r915_source_substance_audit.py \
    > "$OUT/R922_SOURCE_SUBSTANCE_AUDIT.txt"

STARCORE_TOOLCHAIN_ROOT=${STARCORE_TOOLCHAIN_ROOT:-"$ROOT/../TOOLCHAIN_USED"} \
R922_EVIDENCE_DIR="$OUT" ./scripts/r922_compile_host.sh
R915_EVIDENCE_DIR="$OUT" ./scripts/r915_real_boundary_gate.sh \
    > "$OUT/R922_REAL_BOUNDARY_REGRESSION.txt"

python3 -m py_compile verification/r922/*.py verification/r919/*.py \
    verification/r915/*.py verification/r914/*.py verification/r912/*.py \
    verification/r911/*.py verification/r910/*.py scripts/r922_generate_r_java.py \
    training/r906/*.py

pass_line '^R922_STATIC_CONTRACT=PASS$' "$OUT/R922_STATIC_CONTRACT.txt" STATIC_CONTRACT
pass_line '^R919_SQLITE_TRUTH_CLOSURE=PASS$' \
    "$OUT/R922_SQLITE_TRUTH_CLOSURE.txt" SQLITE_TRUTH_CLOSURE
pass_line '^R919_DRAW_TASK_CLOSURE=PASS\|TERMINAL=277\|TOTAL=277\|OPEN=0$' \
    "$OUT/R922_SQLITE_TRUTH_CLOSURE.txt" EVERY_DRAW_TASK_CLOSURE
pass_line '^R919_PREDICTION_SETTLEMENT=PASS\|SETTLED=200\|ELIGIBLE=200\|DUPLICATES=0$' \
    "$OUT/R922_SQLITE_TRUTH_CLOSURE.txt" EVERY_PREDICTION_SETTLEMENT
pass_line '^R919_TEACHER_POSTSETTLEMENT=PASS' \
    "$OUT/R922_SQLITE_TRUTH_CLOSURE.txt" TEACHER_POSTSETTLEMENT
pass_line '^R919_RESEARCH_PER_DRAW=PASS\|ALGORITHM=400/400\|ASSET=400/400' \
    "$OUT/R922_SQLITE_TRUTH_CLOSURE.txt" RESEARCH_PER_DRAW
pass_line '^R919_NO_PREDRAW_CONVERGENCE=PASS\|EXCLUDED=77\|PRESSURE_SLICE=4\|PULSES=20$' \
    "$OUT/R922_SQLITE_TRUTH_CLOSURE.txt" PRESSURE_CONVERGENCE
pass_line '^R919_SIDECAR_ISOLATION=PASS' \
    "$OUT/R922_SQLITE_TRUTH_CLOSURE.txt" SIDECAR_ISOLATION
pass_line '^R915_SQLITE_CLOSED_LOOP=PASS$' \
    "$OUT/R922_R915_SQLITE_REGRESSION.txt" R915_SQLITE_REGRESSION
pass_line '^R914_END_TO_END_SETTLEMENT_GATE=PASS$' \
    "$OUT/R922_EVERY_DRAW_SETTLEMENT_REGRESSION.txt" R914_SETTLEMENT_REGRESSION
pass_line '^R911_SOLE_GATE_ORPHAN_RECOVERY=PASS$' \
    "$OUT/R922_SETTLEMENT_STATE_MACHINE.txt" ORPHAN_RECOVERY
pass_line '^CORE_SURVIVES_SIDECAR_FAILURE=PASS$' \
    "$OUT/R922_SIDECAR_FAILURE_INJECTION.txt" CORE_ISOLATION
pass_line '^R912_304_READY_CONVERGENCE=PASS$' \
    "$OUT/R922_BACKLOG_FAIRNESS.txt" BACKLOG_FAIRNESS
pass_line '^R912_SETTLEMENT_DENOMINATOR=PASS' \
    "$OUT/R922_SQLITE_TRUTH_RESEARCH.txt" TWO_DENOMINATORS

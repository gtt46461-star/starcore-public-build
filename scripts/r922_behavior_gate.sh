    "$OUT/R922_RUNTIME_CONTRACT_HARNESS.txt" R922_RUNTIME_CONTRACT
pass_line '^R922_ATOM_STAGE_CONTRACT=PASS\|TOTAL=240\|GROUPS=12\|FAMILIES=72\|PREDRAW=205\|PRODUCTION_SCORE=165\|RESEARCH_PROXY=40\|AUDIT_IDENTITY=15\|SETTLEMENT_EVIDENCE=20' \
    "$OUT/R922_RUNTIME_CONTRACT_HARNESS.txt" ATOM_STAGE_RUNTIME
pass_line '^R922_ATOM_REGISTRY_INTEGRITY=PASS\|EXACT=240/240\|MUTATION_REJECT=1\|MISSING_REJECT=1\|LOSSY_SUBSET_COUNT=FORBIDDEN$' \
    "$OUT/R922_RUNTIME_CONTRACT_HARNESS.txt" ATOM_REGISTRY_INTEGRITY

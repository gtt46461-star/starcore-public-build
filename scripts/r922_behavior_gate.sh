    "$OUT/R922_RUNTIME_CONTRACT_HARNESS.txt" SEMANTIC_ATOMIC_WORLD
pass_line '^R922_ASSET_LEAKAGE_REPAIR=PASS' \
    "$OUT/R922_RUNTIME_CONTRACT_HARNESS.txt" ASSET_LEAKAGE_REPAIR
pass_line '^R922_EVOLUTION_CONTRACT=PASS' \
    "$OUT/R922_RUNTIME_CONTRACT_HARNESS.txt" EVOLUTION_RUNTIME
pass_line '^R922_CONTROLLED_REAL_AUDIT=PASS\|VALID_REAL_ROWS_ALLOWED=1' \

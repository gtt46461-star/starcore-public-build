fail() {
    echo "R915_BEHAVIOR_GATE=FAIL|$1" >&2
    exit 1
}

pass_line() {
    local pattern=$1
    local file=$2
    local code=$3
    rg -q -- "$pattern" "$file" || fail "$code"
}


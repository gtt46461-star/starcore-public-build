#!/usr/bin/env python3
"""D04 same-fold acceptance over the actual D0-D3/Gate9 trainers.

Synthetic chronological history is generated by the production RawUpstreamHarnessR932. This is an
engineering/PIT/parity test only; it is not Future performance evidence and grants no REAL authority.
"""
from __future__ import annotations
import json, sys, tempfile
from pathlib import Path
import numpy as np

R=Path(__file__).resolve().parents[1];sys.path.insert(0,str(R))
from training.r929 import pipeline as p, deep_candidates as d

BASE='BASE_NUMBER_Q_9_EXPERT_MEAN'
CANDIDATES=(BASE,'D0','D1','D2','D3','GATE9')

def check(v,name,checks):
    if not v: raise AssertionError(name)
    checks.append(name);print(name+'=PASS',flush=True)

def load_fixture():
    path=R/'build/r932-model-bundle/raw_upstream.jsonl'
    rows=[json.loads(line) for line in path.read_text().splitlines() if line.strip()][:100]
    if len(rows)!=100: raise AssertionError('D04_RAW_UPSTREAM_100_REQUIRED')
    raw=[json.loads(row['proofs'][0].split('=',1)[1]) for row in rows]
    state=np.asarray([r['states'] for r in raw],dtype=float)
    experts=np.asarray([r['expert_logits'] for r in raw],dtype=float)
    issues=[row['target_issue'] for row in rows]
    # The production RawUpstreamHarness uses actual[p] = (p+t+1)%10 + 1 for row t.
    actual=np.asarray([[(n+t+1)%10+1 for n in range(10)] for t in range(100)],dtype=np.int16)
    y=np.asarray([[int(actual[t,a[0]-1] in a[1:4]) for a in p.ACTIONS] for t in range(100)],dtype=np.int8)
    if y.shape!=(100,1200) or not np.all(y.sum(1)==360): raise AssertionError('D04_K3_LABEL_SURFACE')
    # deep_candidates no longer consumes META96 as an upstream model input, but keeps the row count
    # argument for the common dataset contract. Supplying zeros makes accidental reuse immediately
    # visible if that contract regresses.
    meta=np.zeros((100,1200,96),dtype=np.float64)
    return meta,y,state,experts,issues

def assert_report(report,checks):
    check(report.get('same_folds') is True,'D04_UPSTREAM_SAME_FOLDS',checks)
    folds=report['folds'];check(len(folds)==5,'D04_UPSTREAM_FIVE_FOLDS',checks)
    expected=[([0,25],[25,26],[26,36]),([0,35],[35,36],[36,47]),([0,46],[46,47],[47,58]),([0,57],[57,58],[58,69]),([0,68],[68,69],[69,80])]
    for i,(fold,want) in enumerate(zip(folds,expected)):
        check((fold['train'],fold['embargo'],fold['test'])==want,'D04_UPSTREAM_FOLD_%d_BOUNDARY'%i,checks)
        check(tuple(fold['models'].keys())==CANDIDATES,'D04_UPSTREAM_FOLD_%d_ALL_CANDIDATES'%i,checks)
        for name in CANDIDATES:
            row=fold['models'][name]
            check(('status' in row and row['status']=='FAILED') or ('cross_entropy' in row and row.get('n_issues',0)>0),
                  'D04_UPSTREAM_FOLD_%d_%s_RESULT_OR_FAILURE'%(i,name),checks)
    check(tuple(report['candidate_metrics'].keys())==CANDIDATES,'D04_UPSTREAM_TUNE_ALL_CANDIDATES',checks)

def main():
    checks=[];meta,y,state,experts,issues=load_fixture();splits={'train':[0,80],'tune':[81,100]}
    out=R/'reports/r932/d04_final/upstream_fold';out.mkdir(parents=True,exist_ok=True)
    report=d.compare(meta,y,p.ACTIONS,issues,splits,out,p.write_json,p.digest,p.canonical,raw_state=state,raw_experts=experts)
    assert_report(report,checks)
    check(report['tune_champion'] in CANDIDATES,'D04_UPSTREAM_TUNE_CHAMPION_LEGAL',checks)
    check(report.get('production_switch') is False,'D04_TUNE_COMPARISON_CANNOT_DIRECTLY_SWITCH_PRODUCTION',checks)

    # Failure retention: place the chronology gap inside the common prefix consumed by every
    # registered D04 fold. D2 must remain present and explicitly FAILED in TUNE and every fold.
    broken=list(issues);broken[1]='202609110999'
    with tempfile.TemporaryDirectory(prefix='r932-d04-gap-') as td:
        failed=d.compare(meta,y,p.ACTIONS,broken,splits,Path(td),p.write_json,p.digest,p.canonical,raw_state=state,raw_experts=experts)
    check(failed['candidate_metrics']['D2'].get('status')=='FAILED','D04_D2_GAP_TUNE_FAILURE_RETAINED',checks)
    check(all(f['models']['D2'].get('status')=='FAILED' for f in failed['folds']),'D04_D2_GAP_ALL_FOLD_FAILURES_RETAINED',checks)

    # Exercise the actual compare selector under a no-gain surface by replacing metrics only; model
    # fitting/fold construction stays real. Equal candidate metrics must retain the simple baseline.
    original=d.metrics
    def equal_metrics(q,labels):
        n=len(q);return {'n_issues':n,'cross_entropy':1.0,'top1':.1,'top3':.3,
                         'per_position_top1':[.1]*10,'brier':.5,'row_error':0.0,
                         'column_error':0.0,'finite_nonnegative':True}
    d.metrics=equal_metrics
    try:
        with tempfile.TemporaryDirectory(prefix='r932-d04-nogain-') as td:
            equal=d.compare(meta,y,p.ACTIONS,issues,splits,Path(td),p.write_json,p.digest,p.canonical,raw_state=state,raw_experts=experts)
    finally:
        d.metrics=original
    check(equal['tune_champion']==BASE,'D04_NO_GAIN_RETAINS_NUMBER_BASELINE',checks)

    summary={'status':'PASS','scope':'SYNTHETIC_PRODUCTION_CAPTURE_ACTUAL_D0_D3_GATE9_TRAINERS_NOT_FUTURE_EFFECT',
             'checks':checks,'passed':len(checks),'failed':0,'candidates':list(CANDIDATES),
             'folds':report['folds'],'tune_champion':report['tune_champion'],'effect_proven':False,
             'may_authorize_real':False}
    target=R/'reports/r932/d04_final/UPSTREAM_FOLD_ACCEPTANCE.json';p.write_json(target,summary)
    print('R932_D04_UPSTREAM_FOLD_ACCEPTANCE_PASS|checks=%d|folds=5'%len(checks))

if __name__=='__main__':main()

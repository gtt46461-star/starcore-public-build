#!/usr/bin/env bash
set -euo pipefail

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
OUT=${R919_EVIDENCE_DIR:-"$ROOT/build/r919-verification/evidence"}
AUDIT=${R919_SOURCE_AUDIT_DIR:-"$ROOT/build/r919-verification/source-audit"}
mkdir -p "$OUT" "$AUDIT"
cd "$ROOT"

fail() {
    echo "R919_BEHAVIOR_GATE=FAIL|$1" >&2
    exit 1
}

pass_line() {
    local pattern=$1
    local file=$2
    local code=$3
    rg -q -- "$pattern" "$file" || fail "$code"
}

python3 verification/r919/r919_static_contract.py > "$OUT/R919_STATIC_CONTRACT.txt"
python3 verification/r919/r919_sqlite_truth_closure.py > "$OUT/R919_SQLITE_TRUTH_CLOSURE.txt"
python3 verification/r915/r915_sqlite_closed_loop.py > "$OUT/R919_R915_SQLITE_REGRESSION.txt"
python3 verification/r914/r914_end_to_end_settlement_gate.py \
    > "$OUT/R919_EVERY_DRAW_SETTLEMENT_REGRESSION.txt"
python3 verification/r911/r911_sqlite_runtime_gate.py \
    > "$OUT/R919_SQLITE_MIGRATION_RUNTIME.txt"
python3 verification/r911/r911_settlement_state_machine.py \
    > "$OUT/R919_SETTLEMENT_STATE_MACHINE.txt"
python3 verification/r910/r910_settlement_core_isolation.py \
    > "$OUT/R919_SIDECAR_FAILURE_INJECTION.txt"
python3 verification/r912/r912_settlement_fairness.py \
    > "$OUT/R919_BACKLOG_FAIRNESS.txt"
python3 verification/r912/r912_sqlite_truth_and_research.py \
    > "$OUT/R919_SQLITE_TRUTH_RESEARCH.txt"

R915_BASE_COMMIT=${R919_BASE_COMMIT:-cef09f8} \
R915_SOURCE_AUDIT_DIR="$AUDIT" \
python3 verification/r915/r915_source_substance_audit.py \
    > "$OUT/R919_SOURCE_SUBSTANCE_AUDIT.txt"

STARCORE_TOOLCHAIN_ROOT=${STARCORE_TOOLCHAIN_ROOT:-"$ROOT/../TOOLCHAIN_USED"} \
R919_EVIDENCE_DIR="$OUT" ./scripts/r919_compile_host.sh
R915_EVIDENCE_DIR="$OUT" ./scripts/r915_real_boundary_gate.sh \
    > "$OUT/R919_REAL_BOUNDARY_REGRESSION.txt"

python3 -m py_compile verification/r919/*.py verification/r915/*.py \
    verification/r914/*.py verification/r912/*.py verification/r911/*.py \
    verification/r910/*.py training/r906/*.py

pass_line '^R919_STATIC_CONTRACT=PASS$' "$OUT/R919_STATIC_CONTRACT.txt" STATIC_CONTRACT
pass_line '^R919_SQLITE_TRUTH_CLOSURE=PASS$' \
    "$OUT/R919_SQLITE_TRUTH_CLOSURE.txt" SQLITE_TRUTH_CLOSURE
pass_line '^R919_DRAW_TASK_CLOSURE=PASS\|TERMINAL=277\|TOTAL=277\|OPEN=0$' \
    "$OUT/R919_SQLITE_TRUTH_CLOSURE.txt" EVERY_DRAW_TASK_CLOSURE
pass_line '^R919_PREDICTION_SETTLEMENT=PASS\|SETTLED=200\|ELIGIBLE=200\|DUPLICATES=0$' \
    "$OUT/R919_SQLITE_TRUTH_CLOSURE.txt" EVERY_PREDICTION_SETTLEMENT
pass_line '^R919_TEACHER_POSTSETTLEMENT=PASS' \
    "$OUT/R919_SQLITE_TRUTH_CLOSURE.txt" TEACHER_POSTSETTLEMENT
pass_line '^R919_RESEARCH_PER_DRAW=PASS\|ALGORITHM=400/400\|ASSET=400/400' \
    "$OUT/R919_SQLITE_TRUTH_CLOSURE.txt" RESEARCH_PER_DRAW
pass_line '^R919_NO_PREDRAW_CONVERGENCE=PASS\|EXCLUDED=77\|PRESSURE_SLICE=4\|PULSES=20$' \
    "$OUT/R919_SQLITE_TRUTH_CLOSURE.txt" PRESSURE_CONVERGENCE
pass_line '^R919_SIDECAR_ISOLATION=PASS' \
    "$OUT/R919_SQLITE_TRUTH_CLOSURE.txt" SIDECAR_ISOLATION
pass_line '^R915_SQLITE_CLOSED_LOOP=PASS$' \
    "$OUT/R919_R915_SQLITE_REGRESSION.txt" R915_SQLITE_REGRESSION
pass_line '^R914_END_TO_END_SETTLEMENT_GATE=PASS$' \
    "$OUT/R919_EVERY_DRAW_SETTLEMENT_REGRESSION.txt" R914_SETTLEMENT_REGRESSION
pass_line '^R911_SOLE_GATE_ORPHAN_RECOVERY=PASS$' \
    "$OUT/R919_SETTLEMENT_STATE_MACHINE.txt" ORPHAN_RECOVERY
pass_line '^CORE_SURVIVES_SIDECAR_FAILURE=PASS$' \
    "$OUT/R919_SIDECAR_FAILURE_INJECTION.txt" CORE_ISOLATION
pass_line '^R912_304_READY_CONVERGENCE=PASS$' \
    "$OUT/R919_BACKLOG_FAIRNESS.txt" BACKLOG_FAIRNESS
pass_line '^R912_SETTLEMENT_DENOMINATOR=PASS' \
    "$OUT/R919_SQLITE_TRUTH_RESEARCH.txt" TWO_DENOMINATORS
pass_line '^R915_SOURCE_SUBSTANCE_AUDIT=PASS' \
    "$OUT/R919_SOURCE_SUBSTANCE_AUDIT.txt" SOURCE_AUDIT
pass_line '^R919_COMPILE_HOST=PASS\|VERSION=V57\.20\.5-R5\.3\.5-919\|VERSION_CODE=577240919\|JAVA=[0-9]+\|CLASS=[0-9]+$' \
    "$OUT/R919_COMPILE_HOST_SUMMARY.txt" JAVA17_FULL_COMPILE
pass_line '^R919_RUNTIME_CONTRACT=PASS$' \
    "$OUT/R919_RUNTIME_CONTRACT_HARNESS.txt" R919_RUNTIME_CONTRACT
pass_line '^R919_ATOM_STAGE_CONTRACT=PASS\|TOTAL=240\|PREDRAW=205\|SETTLEMENT_EVIDENCE=20' \
    "$OUT/R919_RUNTIME_CONTRACT_HARNESS.txt" ATOM_STAGE_RUNTIME
pass_line '^R919_ASSET_LEAKAGE_REPAIR=PASS' \
    "$OUT/R919_RUNTIME_CONTRACT_HARNESS.txt" ASSET_LEAKAGE_REPAIR
pass_line '^R919_UNIFIED_RUNTIME_TRUTH=PASS\|WHY_CARDS=4\|STATE_BOXES=16' \
    "$OUT/R919_RUNTIME_CONTRACT_HARNESS.txt" UNIFIED_TRUTH_RUNTIME
pass_line '^R915_REAL_BOUNDARY=PASS$' \
    "$OUT/R919_REAL_BOUNDARY_REGRESSION.txt" CONTROLLED_REAL_BOUNDARY
pass_line '^STATUS=PASS$' "$OUT/R919_FORMULA_96X120.txt" FORMULA_96X120
pass_line '^ONLINE_SETTLED_LABEL_UPDATE=PASS$' \
    "$OUT/R919_TINY_DEEP_HARNESS.txt" TINY_DEEP_ONLINE_UPDATE

JAVA_COUNT=$(find app/src/main/java -name '*.java' | wc -l)
{
    echo 'R919_BEHAVIOR_GATE=PASS'
    echo 'VERSION_IDENTITY=V57.20.5-R5.3.5-919/577240919'
    echo 'BACKGROUND_STATIC_START_STICKY_TASK_REMOVED_ALARM_JOB_BOOT=PASS'
    echo 'BACKGROUND_RUNTIME_GRANTS_AND_LAST_OBSERVED_VISIBLE=PASS'
    echo 'PHYSICAL_DEVICE_BACKGROUND_RUNTIME=RETEST_REQUIRED'
    echo 'DRAW_TASK_EVERY_FETCHED_ISSUE=PASS'
    echo 'PREDICTED_ISSUE_EXACTLY_ONCE_SETTLEMENT=PASS'
    echo 'TEACHER_FORWARD_REVERSE_CAUSAL_FEEDBACK_POSTSETTLEMENT=PASS'
    echo 'NO_PREDRAW_BACKLOG_PRESSURE_CONVERGENCE=PASS'
    echo 'ATOM_240_STAGE_TYPED_A9_POSTDRAW_ONLY=PASS'
    echo 'GENESIS_ASSET_STATE_SCORE_UPDATE_CHINESE_NAME=PASS'
    echo 'ALGORITHM_STATE_SCORE_UPDATE_CHINESE_NAME=PASS'
    echo 'FAILURE_VECTOR_STRUCTURAL_EVOLUTION=PASS'
    echo 'FUTURE_OOS_MULTI_METRIC_PRUNE_CERTIFY=PASS'
    echo 'RESEARCH_DIRECT_REAL_AUTHORITY=FORBIDDEN'
    echo 'UNIFIED_UI_TRUTH_WHY4_STATE16=PASS'
    echo 'JAVA17_FULL_COMPILE=PASS'
    echo "JAVA_SOURCE_SUBSTANCE=$JAVA_COUNT/EMPTY0/TRIVIAL0"
} | tee "$OUT/R919_BEHAVIOR_GATE_SUMMARY.txt"

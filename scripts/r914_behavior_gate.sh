#!/usr/bin/env bash
set -euo pipefail

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
OUT=${R914_EVIDENCE_DIR:-"$ROOT/build/r914-verification/evidence"}
mkdir -p "$OUT"
cd "$ROOT"

fail() {
    echo "R914_BEHAVIOR_GATE=FAIL|$1" >&2
    exit 1
}

pass_line() {
    local pattern=$1
    local file=$2
    local code=$3
    rg -q -- "$pattern" "$file" || fail "$code"
}

python3 verification/r914/r914_static_contract.py \
    > "$OUT/R914_STATIC_CONTRACT.txt"
python3 verification/r914/r914_end_to_end_settlement_gate.py \
    > "$OUT/R914_END_TO_END_SETTLEMENT.txt"

# Keep the earlier real-SQLite and fault-injection proofs in the final gate. R914 must preserve
# every previously closed invariant while adding non-blocking live scheduling and richer truth.
python3 verification/r911/r911_sqlite_runtime_gate.py \
    > "$OUT/R914_SQLITE_MIGRATION_RUNTIME.txt"
python3 verification/r911/r911_settlement_state_machine.py \
    > "$OUT/R914_SETTLEMENT_STATE_MACHINE.txt"
python3 verification/r910/r910_settlement_core_isolation.py \
    > "$OUT/R914_SIDECAR_FAILURE_INJECTION.txt"
python3 verification/r912/r912_settlement_fairness.py \
    > "$OUT/R914_BACKLOG_FAIRNESS.txt"
python3 verification/r912/r912_sqlite_truth_and_research.py \
    > "$OUT/R914_SQLITE_TRUTH_RESEARCH.txt"

STARCORE_TOOLCHAIN_ROOT=${STARCORE_TOOLCHAIN_ROOT:-"$ROOT/../TOOLCHAIN_USED"} \
R914_EVIDENCE_DIR="$OUT" ./scripts/r914_compile_host.sh
R906_EVIDENCE_DIR="$OUT" ./scripts/r906_real_boundary_gate.sh \
    > "$OUT/R914_REAL_BOUNDARY.txt"
python3 -m py_compile verification/r914/*.py verification/r912/*.py \
    verification/r911/*.py verification/r910/*.py training/r906/*.py

pass_line '^R914_STATIC_CONTRACT=PASS\|JAVA=512$' \
    "$OUT/R914_STATIC_CONTRACT.txt" STATIC_MAINLINE
pass_line '^R914_END_TO_END_SETTLEMENT_GATE=PASS$' \
    "$OUT/R914_END_TO_END_SETTLEMENT.txt" END_TO_END_SETTLEMENT
pass_line '^R914_DRAW_TASK_CLOSURE=PASS\|TERMINAL=110\|TOTAL=110\|PULSES=111$' \
    "$OUT/R914_END_TO_END_SETTLEMENT.txt" EVERY_DRAW_TASK_CLOSURE
pass_line '^R914_PREDRAW_SETTLEMENT=PASS\|SETTLED=100\|ELIGIBLE=100$' \
    "$OUT/R914_END_TO_END_SETTLEMENT.txt" PREDRAW_SETTLEMENT_DENOMINATOR
pass_line '^R914_EXACTLY_ONCE_LABEL=PASS\|DUPLICATES=0\|TRANSIENT_RETRY=1$' \
    "$OUT/R914_END_TO_END_SETTLEMENT.txt" EXACTLY_ONCE_LABEL
pass_line '^R910_LEGACY_RANK_COLUMN_MIGRATION=PASS$' \
    "$OUT/R914_SQLITE_MIGRATION_RUNTIME.txt" SQLITE_MIGRATION
pass_line '^R911_SOLE_GATE_ORPHAN_RECOVERY=PASS$' \
    "$OUT/R914_SETTLEMENT_STATE_MACHINE.txt" ORPHAN_RECOVERY
pass_line '^R911_304_READY_CONVERGENCE=PASS$' \
    "$OUT/R914_SETTLEMENT_STATE_MACHINE.txt" REPORT_SHAPED_BACKLOG
pass_line '^CORE_SURVIVES_SIDECAR_FAILURE=PASS$' \
    "$OUT/R914_SIDECAR_FAILURE_INJECTION.txt" SETTLEMENT_CORE_ISOLATION
pass_line '^R912_304_READY_CONVERGENCE=PASS$' \
    "$OUT/R914_BACKLOG_FAIRNESS.txt" BACKLOG_FAIRNESS
pass_line '^R912_SETTLEMENT_DENOMINATOR=PASS' \
    "$OUT/R914_SQLITE_TRUTH_RESEARCH.txt" SQLITE_TWO_DENOMINATORS
pass_line '^R912_ALGORITHM_ONLY_PENDING_DISCOVERY=PASS$' \
    "$OUT/R914_SQLITE_TRUTH_RESEARCH.txt" ALGORITHM_PENDING_DISCOVERY
pass_line '^R914_COMPILE_HOST=PASS\|VERSION=V57\.20\.0-R5\.3\.0-914\|VERSION_CODE=577240914\|JAVA=512\|CLASS=' \
    "$OUT/R914_COMPILE_HOST_SUMMARY.txt" JAVA17_FULL_COMPILE
pass_line '^STATUS=PASS$' "$OUT/R914_FORMULA_96X120.txt" FORMULA_96X120
pass_line '^R914_BEHAVIOR_NOVELTY=PASS\|STRUCTURE_DIFFERENT=1\|BEHAVIOR_SAME=1$' \
    "$OUT/R914_RUNTIME_CONTRACT_HARNESS.txt" BEHAVIOR_NOVELTY
pass_line '^R914_ALGORITHM_STATE_NAME=PASS\|NAME=.+算法·第03代\|CELL=' \
    "$OUT/R914_RUNTIME_CONTRACT_HARNESS.txt" CHINESE_MECHANISM_NAME
pass_line '^R914_FUTURE_EVIDENCE=PASS\|GOOD=CHALLENGER_FUTURE_OOS\|BAD_ECE=ECE_UNCALIBRATED\|BAD_COVERAGE=PREDRAW_COVERAGE_TOO_LOW$' \
    "$OUT/R914_RUNTIME_CONTRACT_HARNESS.txt" MULTI_METRIC_FUTURE_OOS
pass_line '^ONLINE_SETTLED_LABEL_UPDATE=PASS$' \
    "$OUT/R914_TINY_DEEP_HARNESS.txt" ONLINE_DEEP_UPDATE
pass_line '^R912_ALGORITHM_EVIDENCE_POLICY=PASS$' \
    "$OUT/R914_ALGORITHM_EVIDENCE_HARNESS.txt" ALGORITHM_EVIDENCE_POLICY
pass_line '^R906_REAL_BOUNDARY=PASS$' "$OUT/R914_REAL_BOUNDARY.txt" REAL_BOUNDARY

{
    echo 'R914_BEHAVIOR_GATE=PASS'
    echo 'DRAW_TASK_EVERY_ISSUE=PASS'
    echo 'PREDRAW_SETTLEMENT_TWO_DENOMINATORS=PASS'
    echo 'EXACTLY_ONCE_OOS_LABEL=PASS'
    echo 'RESTART_ORPHAN_AND_FALSE_TERMINAL_RECOVERY=PASS'
    echo 'CURRENT_PREDRAW_NOT_BLOCKED_BY_SETTLEMENT_BACKLOG=PASS'
    echo 'SETTLEMENT_CORE_SIDECAR_ISOLATION=PASS'
    echo 'JAVA17_FULL_COMPILE=PASS'
    echo 'FORMULA_ASSETS_96X120=PASS'
    echo 'DEEP_LEARNING_ONLINE_FUTURE_ONLY=PASS'
    echo 'ALGORITHM_FAMILY_STATE_SCORE_UPDATE=PASS'
    echo 'ALGORITHM_BEHAVIOR_NOVELTY_AND_CHINESE_NAME=PASS'
    echo 'ALGORITHM_MULTI_METRIC_FUTURE_OOS=PASS'
    echo 'UI_WHY_4_AND_STATE_16=PASS'
    echo 'REAL_BOUNDARY=PASS'
    echo 'PHYSICAL_DEVICE_RUNTIME=RETEST_REQUIRED'
} | tee "$OUT/R914_BEHAVIOR_GATE_SUMMARY.txt"

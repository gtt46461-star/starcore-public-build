#!/usr/bin/env python3
"""Compile the pure Java protocol and execute real SQLite fault/owner fixtures.

The SQLite adapter below is a CONTRACT FIXTURE, not the Android production adapter.
Archive SQL and base guard SQL are generated by extracted, unchanged 095 owner code.
"""
from __future__ import annotations
import argparse
import base64

HERE = Path(__file__).resolve().parent.parent
SOURCE = HERE / 'after_full/app/src/main/java/com/ethk3/novaonepro/strategyv2/SchemaUnitPlanR34.java'
JOURNAL = HERE / 'sql/schema_unit_journal.sql'

def digest(value):
    return hashlib.sha256(value if isinstance(value, bytes) else value.encode()).hexdigest()

def method(text, marker):
    start = text.index(marker)
    opening = text.index('{', start)
    level = 1
    # These three extracted methods contain balanced braces in their SQL/string literals.
    for end in range(opening + 1, len(text)):
        if text[end] == '{': level += 1
        elif text[end] == '}': level -= 1
        if not level: return text[start:end + 1]
    raise ValueError('unclosed owner method')

def root(db):
    rows = db.execute('SELECT event_id,issue_ordinal,source_hash,hex(payload),typeof(payload),ready_at FROM r26_feedback ORDER BY event_id').fetchall()
    return digest(json.dumps(rows, ensure_ascii=False, separators=(',', ':')))

def norm(sql):
    return sql.replace('CREATE TRIGGER IF NOT EXISTS ', 'CREATE TRIGGER ', 1).strip()

def install_fixture(dbpath, fixture, mode='normal'):
    db = sqlite3.connect(dbpath, timeout=0.05, isolation_level=None)
    db.execute('PRAGMA foreign_keys=ON')
    try:
        db.execute('BEGIN IMMEDIATE')
        old = db.execute('SELECT payload_hash FROM r34_schema_unit_receipt WHERE commit_key=?', (fixture['key'],)).fetchone()
        if old:
            if old[0] != fixture['payload']: raise RuntimeError('FIXTURE_RECEIPT_HASH_CONFLICT')
            db.rollback(); print('ALREADY_APPLIED'); return
        row = db.execute('SELECT revision,owner_epoch,owner_fence,next_index FROM r34_schema_unit_run WHERE run_id=?', ('run',)).fetchone()
        if row != (0, 'boot-a', fixture['fence'], 0): raise RuntimeError('STALE_OWNER_OR_CURSOR')
        if db.execute('PRAGMA schema_version').fetchone()[0] != fixture['schema_cookie']:
            raise RuntimeError('REPREPARE_SCHEMA_COOKIE')
        if root(db) != fixture['root']: raise RuntimeError('REPREPARE_ORIGINAL_INPUT')
        for name, expected in fixture['guards']:
            existing = db.execute('SELECT type,sql FROM sqlite_master WHERE name=?', (name,)).fetchone()
            if existing and (existing[0] != 'trigger' or norm(existing[1]) != norm(expected)):
                raise RuntimeError('EXACT_GUARD_MISMATCH')
        db.execute(fixture['archive_sql'])
        db.execute('INSERT INTO r30_retention_archive_index VALUES(?,?,?,?,0,0)',
                   ('r26_feedback', 'r30_keep_r26_feedback', fixture['columns_hash'], fixture['columns_json']))
        for _, sql in fixture['guards']: db.execute(sql)
        for name, expected in fixture['guards']:
            actual = db.execute('SELECT sql FROM sqlite_master WHERE name=?', (name,)).fetchone()
            if not actual or norm(actual[0]) != norm(expected): raise RuntimeError('EXACT_GUARD_MISMATCH')
        if root(db) != fixture['root']: raise RuntimeError('PROTECTED_ORIGINAL_CHANGED')
        after = db.execute('PRAGMA schema_version').fetchone()[0]
        db.execute('INSERT INTO r34_schema_unit_receipt VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)',
                   (fixture['key'], 'run', fixture['plan'], 'INSTALL', 0, 'r26_feedback', 0,
                    0, 1, 'boot-a', fixture['fence'], fixture['payload'], fixture['definition'],
                    fixture['root'], fixture['schema_cookie'], after, 1))
        changed = db.execute("UPDATE r34_schema_unit_run SET next_index=1,revision=1,last_commit_key=?,updated_at=1 WHERE run_id='run' AND revision=0 AND owner_epoch='boot-a' AND owner_fence=? AND next_index=0", (fixture['key'], fixture['fence'])).rowcount
        if changed != 1: raise RuntimeError('STALE_OWNER_OR_CURSOR')
        if mode == 'crash_before_commit': os._exit(73)
        db.commit()
        if mode == 'crash_after_commit': os._exit(74)
        print('COMMITTED')
    except BaseException:
        db.rollback()
        raise
    finally:
        db.close()

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--baseline', type=Path, required=False)
    parser.add_argument('--worker', type=Path)
    parser.add_argument('--fixture', type=Path)
    parser.add_argument('--mode', default='normal')
    args = parser.parse_args()
    if args.worker:
        install_fixture(args.worker, json.loads(args.fixture.read_text()), args.mode); return
    if not args.baseline: parser.error('--baseline required')
    base = args.baseline.resolve()
    src = base / 'app/src/main/java/com/ethk3/novaonepro/strategyv2'
    registry = (src / 'ResearchRetentionR30.java').read_text()
    expected_tables = re.findall(r'"([a-z0-9_]+)"', registry.split('PROTECTED_TABLES=', 1)[1].split('));', 1)[0])
    actual_tables = re.findall(r'"([a-z0-9_]+)"', SOURCE.read_text().split('PROTECTED_TABLES_095 =', 1)[1].split('));', 1)[0])
    assert actual_tables == expected_tables, 'actual 095 protected registry differs'
    owner = (src / 'ResearchRetentionStoreR30.java').read_text()
    runtime_schema = (src / 'RuntimeSchemaR26.java').read_text()
    feedback_sql = re.search(r'public static final String FEEDBACK = "([^"]+)";', runtime_schema).group(1)
    index_sql = re.search(r'public static final String INDEX_DDL="([^"]+)";', owner).group(1)
    extracted = [method(owner, marker) for marker in (
        'static String q(', 'static String lit(', 'private static LinkedHashMap<String,String> guardsR31(',
        'private static String archiveDdlR31(')]
    receipts = []
    with tempfile.TemporaryDirectory(prefix='r34-schema-') as directory:
        tmp = Path(directory); classes = tmp / 'classes'; classes.mkdir()
        owner_java = tmp / 'ExtractedRetentionOwner095.java'
        owner_java.write_text('''package com.ethk3.novaonepro.strategyv2;
import java.util.*;
public final class ExtractedRetentionOwner095 {
''' + '\n'.join(extracted) + '''
public static void main(String[] args) {
 List<String[]> columns=new ArrayList<>();
 for(int i=1;i<args.length;i++)columns.add(args[i].split("\\\\|",-1));
 java.util.Base64.Encoder encoder=java.util.Base64.getEncoder();
 System.out.println(encoder.encodeToString(archiveDdlR31("r30_keep_r26_feedback",columns).getBytes(java.nio.charset.StandardCharsets.UTF_8)));
 for(Map.Entry<String,String> guard:guardsR31("r26_feedback",columns,args[0]).entrySet())
  System.out.println(guard.getKey()+"\\t"+encoder.encodeToString(guard.getValue().getBytes(java.nio.charset.StandardCharsets.UTF_8)));
}
}
''')
        # Runtime has jdk.compiler but no javac launcher/ct.sym; scope is stated in receipt.
        compile_result = subprocess.run(['java', '-m', 'jdk.compiler/com.sun.tools.javac.Main', '-source', '17', '-target', '17', '-d', str(classes), str(SOURCE), str(HERE / 'tests/SchemaUnitPlanR34Host.java'), str(owner_java)], capture_output=True, text=True)
        assert compile_result.returncode == 0, compile_result.stdout + compile_result.stderr
        host = subprocess.run(['java', '-cp', str(classes), 'com.ethk3.novaonepro.strategyv2.SchemaUnitPlanR34Host'], capture_output=True, text=True, check=True)
        java_receipt = json.loads(host.stdout)
        probe = sqlite3.connect(':memory:'); probe.execute(feedback_sql)
        columns = [(r[1], r[2], str(r[5])) for r in probe.execute('PRAGMA table_info(r26_feedback)')]
        columns_json = json.dumps(columns, separators=(',', ':')); columns_hash = digest(columns_json)
        rendered = subprocess.run(['java', '-cp', str(classes), 'com.ethk3.novaonepro.strategyv2.ExtractedRetentionOwner095', columns_hash] + ['|'.join(c) for c in columns], capture_output=True, text=True, check=True).stdout.splitlines()
        archive_sql = base64.b64decode(rendered[0]).decode()
        guards = [(line.split('\t', 1)[0], base64.b64decode(line.split('\t', 1)[1]).decode()) for line in rendered[1:]]
        (HERE / 'tests/generated_owner_fixture.json').write_text(json.dumps({'scope': '095 unchanged base guards and archive DDL; specialized owner guards still require Android integration', 'source': 'r26_feedback', 'sourceDDL': feedback_sql, 'archiveDDL': archive_sql, 'guards': guards, 'extractedMethodSha256': [digest(x) for x in extracted]}, ensure_ascii=False, indent=2) + '\n')
        def fresh(name):
            path = tmp / (name + '.db'); db = sqlite3.connect(path, isolation_level=None)
            db.execute('PRAGMA journal_mode=WAL'); db.execute(feedback_sql); db.execute(index_sql); db.executescript(JOURNAL.read_text())
            db.execute('INSERT INTO r26_feedback VALUES(?,?,?,?,?)', ('original-event', 1, digest('draw'), b'\x00\xfforiginal payload\x00', 1))
            db.execute('INSERT INTO r34_schema_unit_run VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)',
                       ('run', 'fixture-db', 'fixture-migration', digest('plan'), 34, 'fixture-def-v1', len(expected_tables), 'INSTALL', 0, 0, 'boot-a', 1, 0, -1, '', 0))
            fixture = {'key': digest('unit0'), 'payload': digest('fixture commit payload'), 'plan': digest('plan'),
                       'definition': digest(json.dumps(guards)), 'root': root(db), 'fence': 1,
                       'schema_cookie': db.execute('PRAGMA schema_version').fetchone()[0], 'archive_sql': archive_sql,
                       'columns_hash': columns_hash, 'columns_json': columns_json, 'guards': guards}
            db.close(); return path, fixture
        def worker(path, fixture, mode='normal'):
            fp = tmp / (path.stem + '.json'); fp.write_text(json.dumps(fixture))
            return subprocess.run([sys.executable, str(Path(__file__).resolve()), '--worker', str(path), '--fixture', str(fp), '--mode', mode], capture_output=True, text=True)
        def assert_unchanged(path, fixture):
            with sqlite3.connect(path) as db:
                assert root(db) == fixture['root']
                assert db.execute('SELECT next_index,revision FROM r34_schema_unit_run').fetchone() == (0, 0)
                assert db.execute('SELECT COUNT(*) FROM r34_schema_unit_receipt').fetchone()[0] == 0
                assert not db.execute("SELECT 1 FROM sqlite_master WHERE name='r30_keep_r26_feedback'").fetchone()
        path, f = fresh('before_commit')
        assert worker(path, f, 'crash_before_commit').returncode == 73
        assert_unchanged(path, f)
        receipts.append('child_process_exit_before_commit_rolls_back_DDL_receipt_cursor')
        path, f = fresh('after_commit')
        assert worker(path, f, 'crash_after_commit').returncode == 74
        retry = worker(path, f); assert retry.returncode == 0 and 'ALREADY_APPLIED' in retry.stdout
        with sqlite3.connect(path) as db:
            assert db.execute('SELECT next_index,revision FROM r34_schema_unit_run').fetchone() == (1, 1)
            assert db.execute('SELECT COUNT(*) FROM r34_schema_unit_receipt').fetchone()[0] == 1
            original = db.execute('SELECT payload,typeof(payload) FROM r26_feedback').fetchone()
            db.execute('DELETE FROM r26_feedback')
            assert db.execute('SELECT payload,typeof(payload) FROM r30_keep_r26_feedback').fetchone() == original
            try: db.execute("UPDATE r30_keep_r26_feedback SET payload='changed'")
            except sqlite3.IntegrityError as e: assert 'PROTECTED_ARCHIVE_IMMUTABLE' in str(e)
            else: raise AssertionError('archive mutation accepted')
        receipts.append('commit_before_ACK_restart_reuses_one_receipt_and_preserves_original_BLOB')
        path, f = fresh('wrong_guard')
        with sqlite3.connect(path) as db:
            name = guards[0][0]
            db.execute(f'CREATE TRIGGER "{name}" BEFORE DELETE ON r26_feedback BEGIN SELECT 1; END')
            f['schema_cookie'] = db.execute('PRAGMA schema_version').fetchone()[0]
        rejected = worker(path, f); assert rejected.returncode != 0 and 'EXACT_GUARD_MISMATCH' in rejected.stderr
        assert_unchanged(path, f)
        receipts.append('same_name_wrong_guard_rejected_without_drop_or_repair')
        path, f = fresh('stale_fence'); f['fence'] = 2
        rejected = worker(path, f); assert rejected.returncode != 0 and 'STALE_OWNER_OR_CURSOR' in rejected.stderr
        assert_unchanged(path, f)
        receipts.append('stale_owner_cannot_create_DDL_or_advance_cursor')
        path, f = fresh('busy_writer'); lock = sqlite3.connect(path, isolation_level=None); lock.execute('BEGIN IMMEDIATE')
        rejected = worker(path, f); assert rejected.returncode != 0 and 'database is locked' in rejected.stderr
        lock.rollback(); lock.close(); assert_unchanged(path, f)
        assert worker(path, f).returncode == 0
        receipts.append('real_SQLite_writer_contention_retries_same_unit_after_lock_release')
        path, f = fresh('cookie_changed')
        with sqlite3.connect(path) as db: db.execute('CREATE INDEX fixture_external_index ON r26_feedback(ready_at)')
        rejected = worker(path, f); assert rejected.returncode != 0 and 'REPREPARE_SCHEMA_COOKIE' in rejected.stderr
        assert_unchanged(path, f)
        receipts.append('schema_changed_after_prepare_rejected_before_mutation')
    report = {'schema': 'R34_SCHEMA_UNIT_SUPPLEMENT_VERIFY_V1', 'baseline': '273641e838e0b8dd842b42a67a674e184942a30a',
              'status': 'HOST_AND_SQLITE_CONTRACTS_PASS', 'protectedRegistryMatches095': True, **java_receipt,
              'sqliteScenarios': receipts, 'sqliteVersion': sqlite3.sqlite_version,
              'compileScope': 'Java21 jdk.compiler -source 17 -target 17; no Android API compilation',
              'productionAndroidOwnerIntegrated': False, 'androidBuild': 'NOT_RUN', 'device': 'NOT_RUN', 'apk': 'NOT_BUILT'}
    (HERE / 'VERIFICATION.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(report, ensure_ascii=False, indent=2))

if __name__ == '__main__': main()
